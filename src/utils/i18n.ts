export function useI18n() {
  const locale = usePreferencesStore((state) => state.locale);
  return {
    locale,
    t: (key: string, params?: Record<string, string | number>) => translate(locale, key, params)
  };
}

export function translate(locale: LocaleId, key: string, params?: Record<string, string | number>) {
  const template = messages[locale][key] ?? messages.en[key] ?? key;
  if (!params) return template;
  return Object.entries(params).reduce((value, [name, replacement]) => value.replaceAll(`{${name}}`, String(replacement)), template);
}
